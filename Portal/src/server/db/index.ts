import postgres from "postgres";

export type Sql = postgres.Sql | postgres.TransactionSql;

const NOVENTA_DIAS_MS = 90 * 24 * 60 * 60 * 1000;

const ESQUEMA = `
CREATE TABLE IF NOT EXISTS productos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT NOT NULL DEFAULT '',
  precio_venta INTEGER NOT NULL,
  precio_compra INTEGER NOT NULL DEFAULT 0,
  cantidad_stock INTEGER NOT NULL DEFAULT 0,
  stock_minimo INTEGER NOT NULL DEFAULT 3,
  mascota TEXT NOT NULL DEFAULT 'UNISEX',
  categoria TEXT NOT NULL DEFAULT 'ACCESORIOS',
  fecha_vencimiento BIGINT,
  peso_kg DOUBLE PRECISION,
  variante TEXT,
  nota_advertencia TEXT,
  es_favorito INTEGER NOT NULL DEFAULT 0,
  pedir_al_proveedor INTEGER NOT NULL DEFAULT 0,
  nota_pedido TEXT,
  fecha_actualizacion BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS fotos_producto (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  ruta_archivo TEXT NOT NULL,
  orden INTEGER NOT NULL DEFAULT 0,
  datos BYTEA,
  mime TEXT
);

CREATE TABLE IF NOT EXISTS ventas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha BIGINT NOT NULL,
  total INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS venta_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id INTEGER NOT NULL REFERENCES ventas(id) ON DELETE CASCADE,
  producto_id INTEGER REFERENCES productos(id) ON DELETE SET NULL,
  nombre_producto TEXT NOT NULL,
  cantidad INTEGER NOT NULL,
  precio_compra INTEGER NOT NULL,
  precio_venta INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS pedidos_clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_cliente TEXT NOT NULL,
  contacto TEXT,
  fecha_pedido BIGINT NOT NULL,
  entregado INTEGER NOT NULL DEFAULT 0,
  pagado INTEGER NOT NULL DEFAULT 0,
  stock_descontado INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS pedido_cliente_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INTEGER NOT NULL REFERENCES pedidos_clientes(id) ON DELETE CASCADE,
  producto_id INTEGER REFERENCES productos(id) ON DELETE SET NULL,
  nombre_producto TEXT NOT NULL,
  cantidad INTEGER NOT NULL,
  precio_compra INTEGER NOT NULL DEFAULT 0,
  precio_unitario INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "timestamp" BIGINT NOT NULL,
  nivel TEXT NOT NULL,
  modulo TEXT NOT NULL,
  mensaje TEXT NOT NULL,
  excepcion TEXT
);

CREATE TABLE IF NOT EXISTS meta (
  clave TEXT PRIMARY KEY,
  valor TEXT NOT NULL
);
`;

const TABLAS_IDENTIDAD = [
  "productos",
  "fotos_producto",
  "ventas",
  "venta_items",
  "pedidos_clientes",
  "pedido_cliente_items",
] as const;

let instancia: postgres.Sql | null = null;
let lista: Promise<postgres.Sql> | null = null;

function urlConexion(): string {
  const url =
    process.env.STORAGE_POSTGRES_URL ??
    process.env.POSTGRES_URL ??
    process.env.DATABASE_URL ??
    process.env.STORAGE_POSTGRES_URL_NON_POOLING;
  if (!url) {
    throw new Error(
      "Falta la URL de Postgres. Define STORAGE_POSTGRES_URL (integración Supabase/Vercel) o DATABASE_URL en .env.local.",
    );
  }
  return url;
}

export function conexion(): postgres.Sql {
  if (instancia) return instancia;
  instancia = postgres(urlConexion(), {
    // El pooler de Supabase (pgbouncer) no admite prepared statements.
    prepare: false,
    max: 5,
  });
  return instancia;
}

// Devuelve la conexión garantizando que el esquema ya existe (memoizado).
export function abrirDb(): Promise<postgres.Sql> {
  if (!lista) {
    const sql = conexion();
    lista = sql
      .unsafe(ESQUEMA)
      .simple()
      .then(() => sql)
      .catch((error) => {
        lista = null;
        throw error;
      });
  }
  return lista;
}

export function transaccion<T>(fn: (sql: postgres.TransactionSql) => Promise<T>): Promise<T> {
  return abrirDb().then((sql) => sql.begin(fn));
}

export async function ejecutarInit(): Promise<void> {
  const db = await abrirDb();
  await db`DELETE FROM logs WHERE "timestamp" < ${Date.now() - NOVENTA_DIAS_MS}`;
}

// Tras restaurar un respaldo con ids explícitos, las secuencias quedan atrás.
export async function sincronizarSecuencias(sql: Sql): Promise<void> {
  for (const tabla of TABLAS_IDENTIDAD) {
    await sql.unsafe(
      `SELECT setval(pg_get_serial_sequence('${tabla}', 'id'), COALESCE((SELECT MAX(id) FROM ${tabla}), 1))`,
    );
  }
}

export function aObjetos<T>(filas: unknown): T[] {
  return (filas as Record<string, unknown>[]).map((f) => ({ ...f }) as T);
}

export function aObjeto<T>(fila: unknown): T | null {
  return fila == null ? null : ({ ...(fila as Record<string, unknown>) } as T);
}
